export function newFareEstimateGap(from, to, meters, displayedFare) {
  const alternative = alternateMeters[Math.min(from, to)]?.[Math.max(from, to)]
  if (alternative === undefined) return undefined

  const alternativeFare = fareForDistance(alternative).new
  const fareDifference = displayedFare - alternativeFare
  if (Math.abs(fareDifference) !== 1 || fareForDistance(meters).new !== displayedFare) return undefined

  return {
    fareDifference,
    metersApart: Math.abs(meters - alternative),
    fareBoundary: maxDistanceForNewFare(Math.min(displayedFare, alternativeFare)),
  }
}
